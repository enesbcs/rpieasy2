_RPI_USABLE_GPIO_CACHE: set[int] | None = None
_IS_RPI_CACHE: bool | None = None


def is_raspberry_pi() -> bool:
    global _IS_RPI_CACHE
    if _IS_RPI_CACHE is not None:
        return _IS_RPI_CACHE
    try:
        with open("/proc/device-tree/model") as f:
            model = f.read().strip("\x00").strip()
    except Exception:
        _IS_RPI_CACHE = False
        return False
    _IS_RPI_CACHE = "raspberry" in model.lower()
    return _IS_RPI_CACHE


def _detect_rpi_usable_gpios() -> set[int]:
    global _RPI_USABLE_GPIO_CACHE
    if _RPI_USABLE_GPIO_CACHE is not None:
        return _RPI_USABLE_GPIO_CACHE
    try:
        with open("/proc/device-tree/model") as f:
            model = f.read().strip("\x00").strip().lower()
    except Exception:
        _RPI_USABLE_GPIO_CACHE = set(range(28))
        return _RPI_USABLE_GPIO_CACHE
    for pattern, gpios in RPI_MODEL_USABLE_GPIO:
        if pattern in model:
            _RPI_USABLE_GPIO_CACHE = gpios
            return gpios
    _RPI_USABLE_GPIO_CACHE = set(range(28))
    return _RPI_USABLE_GPIO_CACHE


