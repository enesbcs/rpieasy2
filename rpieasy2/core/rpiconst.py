def get_discovery_vtypes(sensor_type: int, num_values: int) -> list[int]:
    vtypes = SENSOR_TYPE_TO_DISCOVERY_VTYPES.get(sensor_type, [SENSOR_V_TYPE_SINGLE])
    if len(vtypes) >= num_values:
        return vtypes[:num_values]
    return vtypes + [SENSOR_V_TYPE_SINGLE] * (num_values - len(vtypes))


