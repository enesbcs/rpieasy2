_local_ip: str | None = None
_local_ip_last_refresh: float = 0.0


def get_local_ip() -> str:
    global _local_ip, _local_ip_last_refresh
    now = time.time()
    if _local_ip is not None and now - _local_ip_last_refresh < 60:
        return _local_ip
    import fcntl
    import socket
    import struct
    try:
        result = __import__("subprocess").run(["hostname", "-I"], capture_output=True, text=True, timeout=2)
        if result.returncode == 0 and result.stdout.strip():
            ips = result.stdout.strip().split()
            for ip in ips:
                ip = ip.strip()
                if ip and not ip.startswith("127.") and "." in ip:
                    _local_ip = ip
                    _local_ip_last_refresh = now
                    return _local_ip
    except Exception:
        pass
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        max_iface = 32
        buf = struct.pack("i", max_iface * 32)
        buf = fcntl.ioctl(s.fileno(), 0x8912, buf)
        buflen = struct.unpack("i", buf[:4])[0]
        data = buf[4:4 + buflen]
        for i in range(0, buflen, 32):
            ip_raw = data[i + 20:i + 24]
            ip = socket.inet_ntoa(ip_raw)
            if not ip.startswith("127."):
                s.close()
                _local_ip = ip
                _local_ip_last_refresh = now
                return _local_ip
        s.close()
    except Exception:
        pass
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.connect(("8.8.8.8", 80))
        ip = s.getsockname()[0]
        s.close()
        if ip and not ip.startswith("127."):
            _local_ip = ip
            _local_ip_last_refresh = now
            return _local_ip
    except Exception:
        pass
    return "-"
